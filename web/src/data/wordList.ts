const EPOCH_UTC = Date.UTC(2026, 0, 1); // Jan 1, 2026 = day 0

export function getDayIndex(): number {
  const now = new Date();
  const utc = Date.UTC(now.getFullYear(), now.getMonth(), now.getDate());
  return Math.floor((utc - EPOCH_UTC) / 86400000);
}

export function getTodayWord(): { word: string; dayIndex: number } {
  const dayIndex = getDayIndex();
  const idx = ((dayIndex % WORD_LIST.length) + WORD_LIST.length) % WORD_LIST.length;
  return { word: WORD_LIST[idx], dayIndex };
}

export function isValidWord(word: string): boolean {
  // For now, accept any 5-letter word. Could later check against dictionary.
  return word.length === 5 && /^[а-я]+$/.test(word);
}
